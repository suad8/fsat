export function insightFor(name: string, description?: string | null): MachineInsight | null {
  const haystack = `${name} ${description ?? ""}`;
  // الاسم أولاً — الوصف قد يذكر تقنيات أخرى عرضًا
  const byName = MACHINES.find((machine) => machine.match.test(name));
  if (byName) return byName.insight;
  return MACHINES.find((machine) => machine.match.test(haystack))?.insight ?? null;
}
