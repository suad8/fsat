#!/usr/bin/env node
/**
 * تبديل مزوّد قاعدة البيانات في المخطط: sqlite ⇄ postgresql.
 *
 *   node scripts/switch-provider.mjs postgresql [--root DIR] [--no-generate]
 *   node scripts/switch-provider.mjs sqlite     [--root DIR] [--no-generate]
 *
 * لماذا سكربت؟ لا يكفي تغيير DATABASE_URL: provider في schema.prisma ثابت،
 * وهجرات SQLite (SQL خاصة بـ SQLite) لا تصلح لـ PostgreSQL. الخطوات:
 *
 *   → postgresql
 *     ١. يغيّر provider في prisma/schema.prisma
 *     ٢. ينقل prisma/migrations إلى prisma/migrations.sqlite (للرجوع)
 *     ٣. يولّد هجرة أساس واحدة لـ PostgreSQL من المخطط الحالي كاملاً
 *        (prisma migrate diff --from-empty) ويكتب migration_lock.toml
 *     ٤. prisma generate
 *   → sqlite: العكس (يعيد prisma/migrations.sqlite)
 *
 *  لا يحتاج اتصالاً بأي قاعدة. الاعتماديتان @prisma/adapter-pg و pg تُثبَّتان
 *  يدويًا (npm install) — السكربت لا يضيف اعتمادات. كامل الخطوات في docs/DATA.md.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, renameSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const target = args[0];
const rootIndex = args.indexOf("--root");
const root = path.resolve(rootIndex >= 0 ? args[rootIndex + 1] : path.join(import.meta.dirname, ".."));
const generate = !args.includes("--no-generate");

if (target !== "postgresql" && target !== "sqlite") {
  console.error("الاستعمال: node scripts/switch-provider.mjs <postgresql|sqlite> [--root DIR] [--no-generate]");
  process.exit(1);
}

const schemaPath = path.join(root, "prisma", "schema.prisma");
const migrationsDir = path.join(root, "prisma", "migrations");
const sqliteBackupDir = path.join(root, "prisma", "migrations.sqlite");

const schema = readFileSync(schemaPath, "utf8");
const match = schema.match(/(datasource\s+db\s*\{[^}]*?provider\s*=\s*")(\w+)(")/);
if (!match) {
  console.error("✖ لم أجد datasource db / provider في schema.prisma");
  process.exit(1);
}

const current = match[2];
if (current === target) {
  console.log(`✔ المزوّد هو ${target} بالفعل — لا تغيير.`);
  process.exit(0);
}

const prisma = (...prismaArgs) =>
  execFileSync("npx", ["prisma", ...prismaArgs], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

writeFileSync(schemaPath, schema.replace(match[0], `${match[1]}${target}${match[3]}`));
console.log(`▶ provider: ${current} → ${target}`);

if (target === "postgresql") {
  if (existsSync(sqliteBackupDir)) {
    console.error(`✖ ${sqliteBackupDir} موجود مسبقًا — احذفه أو أعد المزوّد إلى sqlite أولاً.`);
    writeFileSync(schemaPath, schema); // تراجع
    process.exit(1);
  }

  if (existsSync(migrationsDir)) renameSync(migrationsDir, sqliteBackupDir);
  mkdirSync(migrationsDir, { recursive: true });

  const sql = prisma("migrate", "diff", "--from-empty", "--to-schema", "prisma/schema.prisma", "--script")
    .replace(/^Loaded Prisma config.*\n/m, "")
    .trimStart();

  const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const baseline = path.join(migrationsDir, `${stamp}_postgres_baseline`);
  mkdirSync(baseline);
  writeFileSync(
    path.join(baseline, "migration.sql"),
    `-- هجرة أساس PostgreSQL مولَّدة من المخطط الحالي (scripts/switch-provider.mjs).\n-- هجرات SQLite الأصلية محفوظة في prisma/migrations.sqlite.\n\n${sql}`,
  );
  writeFileSync(
    path.join(migrationsDir, "migration_lock.toml"),
    '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
  );
  console.log(`✔ هجرة الأساس: ${path.relative(root, baseline)}`);
} else {
  if (!existsSync(sqliteBackupDir)) {
    console.error("✖ prisma/migrations.sqlite غير موجود — لا أعرف أين هجرات SQLite الأصلية. استعدها من git.");
    writeFileSync(schemaPath, schema);
    process.exit(1);
  }
  rmSync(migrationsDir, { recursive: true, force: true });
  renameSync(sqliteBackupDir, migrationsDir);
  console.log("✔ أُعيدت هجرات SQLite");
}

if (generate) {
  prisma("generate");
  console.log("✔ prisma generate");
}

console.log(
  target === "postgresql"
    ? "\nالتالي: npm install @prisma/adapter-pg pg ← ثم DATABASE_URL=postgresql://… npx prisma migrate deploy"
    : "\nالتالي: DATABASE_URL=file:./dev.db npx prisma migrate deploy",
);
